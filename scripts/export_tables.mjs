// Table generator. Emits LaTeX table bodies (results/latex/tables/*.tex),
// Markdown mirrors, and results/eval/table_manifest.json.
// Tables 1-3 are taxonomy/design tables; Tables 4-5 are data-driven from results/eval and results/.
import { isoStamp, parseArgs, readJsonIfExists, sha256OfFile, writeJson, writeText } from "./eval_lib.mjs";

const TABLE_DIR = "results/latex/tables";
const MANIFEST = "results/eval/table_manifest.json";

function fmtPct(x) {
  return x === null || x === undefined ? "--" : `${(x * 100).toFixed(1)}\\%`;
}
function fmtPctMd(x) {
  return x === null || x === undefined ? "--" : `${(x * 100).toFixed(1)}%`;
}

// ---------- Table 1: failure modes ----------
// Third column is the gate check that blocks each mode (was the snake_case family
// list, which was hard to read; the full family mapping lives in the artifact).
const FAILURE_MODES = [
  ["Wrong-run memory use", "Read memory written under a different run", "same-run"],
  ["Wrong-task / scope leak", "Read memory outside the active task scope", "task/scope"],
  ["Stale / superseded memory", "Read memory invalidated by a later policy or event", "active-status"],
  ["Unauthorized access", "Reader not permitted by the memory's allowed-reader set", "receiver auth"],
  ["Missing critical memory", "Fail to retrieve a fact required for the decision", "bounded admitted set"],
  ["Unreconstructable decision", "Final decision not justifiable from the event graph", "provenance + audit"],
];

function texttt(s) {
  // escape underscores and allow line breaks after them so long monospace scenario names wrap
  // inside narrow fixed-width table columns.
  return `\\texttt{${String(s).replace(/_/g, "\\_\\allowbreak ")}}`;
}

function table1() {
  const rows = FAILURE_MODES.map(([m, d, s]) => `${m} & ${d} & ${s} \\\\`).join("\n");
  const tex = `% Auto-generated by scripts/export_tables.mjs -- do not edit by hand.
\\begin{tabular}{@{}p{0.28\\linewidth}p{0.45\\linewidth}p{0.18\\linewidth}@{}}
\\toprule
\\textbf{Failure mode} & \\textbf{Definition} & \\textbf{Gate predicate} \\\\
\\midrule
${rows}
\\bottomrule
\\end{tabular}`;
  const md = `| Failure mode | Definition | Gate predicate |\n|---|---|---|\n${FAILURE_MODES.map(([m, d, s]) => `| ${m} | ${d} | ${s} |`).join("\n")}`;
  return { tex, md };
}

// ---------- Table 2: protocol conditions and baselines ----------
// Decisive conditions only; the C0--C3 internal ablations (freeform-chat,
// typed-envelope, evidence-capsule, proof/commitment) and the protocol-family
// baselines (a2a/autogen/mpac/mesh/q-kvcomm) are detailed in the supplement.
const CONDITIONS = [
  ["C4 (ungated)", "Causal envelope; ungated shared-memory read, no active-message binding", "baseline"],
  ["C4+filters", "Static run/task/status/reader/policy filters, ABAC, ReBAC, source-exists, capability, oracle retriever", "strong baselines"],
  ["\\textbf{C5 MBM-Core}", "\\textbf{Message-bound reference monitor (treatment)}", "treatment"],
];

function table2() {
  const rows = CONDITIONS.map(([c, d, g]) => `${c} & ${d} & ${g} \\\\`).join("\n");
  // tabularx with an X (auto-fitting) Description column so the table never exceeds the IEEE column.
  const tex = `% Auto-generated by scripts/export_tables.mjs
\\begin{tabularx}{\\linewidth}{@{}>{\\raggedright\\arraybackslash}p{0.20\\linewidth} X >{\\raggedright\\arraybackslash}p{0.15\\linewidth}@{}}
\\toprule
\\textbf{Condition} & \\textbf{Description} & \\textbf{Role} \\\\
\\midrule
${rows}
\\bottomrule
\\end{tabularx}`;
  const md = `| Condition | Description | Role |\n|---|---|---|\n${CONDITIONS.map(([c, d, g]) => `| ${c.replace(/\\textbf\{|\}/g, "")} | ${d.replace(/\\textbf\{|\}/g, "")} | ${g} |`).join("\n")}`;
  return { tex, md };
}

